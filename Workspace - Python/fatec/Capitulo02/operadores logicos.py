# A lista de operadores lógicos em python

# Soma
a = 5 + 3  # Realiza a soma de 5 e 3, resultado: 8

# Subtração
b = 10 - 4  # Subtrai 4 de 10, resultado: 6

# Multiplicação
c = 6 * 7  # Multiplica 6 por 7, resultado: 42

# Divisão
d = 15 / 3  # Divide 15 por 3, resultado: 5.0 (divisão retorna float)

# Divisão inteira
e = 15 // 4  # Divide 15 por 4 e retorna a parte inteira, resultado: 3

# Módulo (resto da divisão)
f = 15 % 4  # Calcula o resto da divisão de 15 por 4, resultado: 3

# Exponenciação
g = 2 ** 3  # Eleva 2 à potência de 3, resultado: 8

# Negação
h = -g  # Inverte o sinal do valor de g, resultado: -8

# Exemplo adicional com números negativos
i = -10 + 5 * (-2) / 3  # Combina vários operadores, resultado: -13.3333...

# Resultados intermediários para visualização
print("Soma:", a)
print("Subtração:", b)
print("Multiplicação:", c)
print("Divisão:", d)
print("Divisão Inteira:", e)
print("Módulo:", f)
print("Exponenciação:", g)
print("Negação:", h)
print("Cálculo combinado:", i)
